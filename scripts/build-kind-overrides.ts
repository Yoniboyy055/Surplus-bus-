/**
 * data/kind_overrides.csv -> lib/opendata/kindOverrides.generated.ts
 *
 * The CSV is the place to fix single rows the title rules get wrong:
 *   feed_key,external_id,kind,reason
 *   gcsurplus_sold,gcs-R5OT0021340,part,"A bumper, not a truck"
 *   ns_surplus,<id>,hide_from_comps,"Negative amount in the source"
 * `kind` is one of the lot kinds (vehicle, heavy_truck, powersport, equipment, trailer, electronics,
 * property, part, bulk, other) or hide_from_comps (keeps the rule kind, leaves the row out of ranges).
 * Source rows are never edited or deleted.
 *
 *   npx tsx scripts/build-kind-overrides.ts           # validate + regenerate
 *   npx tsx scripts/build-kind-overrides.ts --check   # CI: fail if the generated file is stale
 *   npx tsx scripts/build-kind-overrides.ts --sql     # upsert SQL for the optional table (migration 056)
 */
import { readFileSync, writeFileSync } from "fs";
import path from "path";
import { parseCsv } from "../lib/opendata/csv";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CSV = path.join(ROOT, "data/kind_overrides.csv");
const OUT = path.join(ROOT, "lib/opendata/kindOverrides.generated.ts");
const KINDS = ["vehicle", "heavy_truck", "powersport", "equipment", "trailer", "electronics", "property", "part", "bulk", "other"];

export type OverrideRow = { feed_key: string; external_id: string; kind: string | null; hide_from_comps: boolean; reason: string };

export function readOverrides(text = readFileSync(CSV, "utf8")): OverrideRow[] {
  const { headers, rows } = parseCsv(text);
  if (headers.join(",") !== "feed_key,external_id,kind,reason") throw new Error("header must be feed_key,external_id,kind,reason");
  const seen = new Set<string>();
  const out: OverrideRow[] = [];
  rows.forEach((r, i) => {
    const line = i + 2;
    const feed = (r.feed_key || "").trim();
    const id = (r.external_id || "").trim();
    const kind = (r.kind || "").trim();
    const reason = (r.reason || "").trim();
    if (!/^(gcsurplus_sold|ns_surplus)$/.test(feed)) throw new Error(`line ${line}: feed_key must be gcsurplus_sold or ns_surplus`);
    if (!/^[A-Za-z0-9._:-]{1,80}$/.test(id)) throw new Error(`line ${line}: bad external_id`);
    if (kind !== "hide_from_comps" && !KINDS.includes(kind)) throw new Error(`line ${line}: kind must be one of ${KINDS.join(", ")} or hide_from_comps`);
    if (reason.length < 5) throw new Error(`line ${line}: give a reason`);
    const key = `${feed}|${id}`;
    if (seen.has(key)) throw new Error(`line ${line}: duplicate ${key}`);
    seen.add(key);
    out.push({ feed_key: feed, external_id: id, kind: kind === "hide_from_comps" ? null : kind, hide_from_comps: kind === "hide_from_comps", reason });
  });
  return out;
}

export function renderGenerated(rows: OverrideRow[]): string {
  return `// GENERATED by scripts/build-kind-overrides.ts from data/kind_overrides.csv. Do not edit by hand.
import type { LotKind } from "./kinds";
export const KIND_OVERRIDES: Array<{ feed_key: string; external_id: string; kind: LotKind | null; hide_from_comps: boolean; reason: string }> = ${JSON.stringify(rows, null, 2)};
`;
}

const sqlStr = (s: string | null) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);

if (process.argv[1] && /build-kind-overrides/.test(process.argv[1])) {
  const rows = readOverrides();
  const gen = renderGenerated(rows);
  if (process.argv.includes("--check")) {
    const cur = readFileSync(OUT, "utf8");
    if (cur !== gen) {
      console.error("kindOverrides.generated.ts is stale: run npx tsx scripts/build-kind-overrides.ts");
      process.exit(1);
    }
    console.log(`kind overrides OK (${rows.length} rows)`);
  } else if (process.argv.includes("--sql")) {
    console.log("-- Upsert for public.lot_kind_overrides (migration 056). Review before running; not run automatically.");
    for (const r of rows)
      console.log(
        `insert into public.lot_kind_overrides (feed_key, external_id, kind, hide_from_comps, reason) values (${sqlStr(r.feed_key)}, ${sqlStr(r.external_id)}, ${sqlStr(r.kind)}, ${r.hide_from_comps}, ${sqlStr(r.reason)}) on conflict (feed_key, external_id) do update set kind = excluded.kind, hide_from_comps = excluded.hide_from_comps, reason = excluded.reason, updated_at = now();`
      );
  } else {
    writeFileSync(OUT, gen);
    console.log(`wrote ${path.relative(ROOT, OUT)} (${rows.length} rows)`);
  }
}
